// Generates Shotz's icon path table from the vendored Phosphor SVGs (no resource bundles).
//
//   swift scripts/gen-icons.swift [--vendor <phosphor-core>/assets/regular]
//
// Reads ThirdParty/phosphor/icons.txt (one upstream icon name per line). With --vendor, copies
// exactly those SVGs from an upstream checkout into ThirdParty/phosphor/regular/ first. Then:
//   - writes Sources/ShotzCore/Icons/PhosphorGlyphs.generated.swift (name → SVG path data),
//   - rewrites THIRD-PARTY-NOTICES (licence text verbatim from ThirdParty/phosphor/LICENSE,
//     source details from ThirdParty/phosphor/SOURCE, and the list of icons used).
// Run from the repository root.
import Foundation

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("gen-icons: \(message)\n".utf8))
    exit(1)
}

let root = URL(filePath: FileManager.default.currentDirectoryPath)
let phosphor = root.appending(path: "ThirdParty/phosphor")
let svgDir = phosphor.appending(path: "regular")

guard let list = try? String(contentsOf: phosphor.appending(path: "icons.txt"), encoding: .utf8) else {
    fail("run from the repository root (ThirdParty/phosphor/icons.txt not found)")
}
let names = list.split(separator: "\n").map { $0.trimmingCharacters(in: .whitespaces) }
    .filter { !$0.isEmpty && !$0.hasPrefix("#") }.sorted()

let args = CommandLine.arguments
if let i = args.firstIndex(of: "--vendor"), i + 1 < args.count {
    let upstream = URL(filePath: args[i + 1])
    try? FileManager.default.createDirectory(at: svgDir, withIntermediateDirectories: true)
    // Remove SVGs no longer listed, then copy the listed ones.
    for file in (try? FileManager.default.contentsOfDirectory(atPath: svgDir.path())) ?? [] where file.hasSuffix(".svg") {
        if !names.contains(String(file.dropLast(4))) { try? FileManager.default.removeItem(at: svgDir.appending(path: file)) }
    }
    for name in names {
        let src = upstream.appending(path: "\(name).svg"), dst = svgDir.appending(path: "\(name).svg")
        guard FileManager.default.fileExists(atPath: src.path()) else { fail("upstream has no \(name).svg") }
        try? FileManager.default.removeItem(at: dst)
        do { try FileManager.default.copyItem(at: src, to: dst) } catch { fail("copy \(name): \(error)") }
    }
}

// Extract path data. Phosphor's regular SVGs are a viewBox 0 0 256 256 with <path d="…"/>
// elements only; anything else is rejected so nothing is silently dropped.
var entries: [(String, String)] = []
let elementPattern = try! NSRegularExpression(pattern: #"<([a-zA-Z]+)\b"#)
let dPattern = try! NSRegularExpression(pattern: #"<path\b[^>]*\bd="([^"]+)""#)
for name in names {
    guard let svg = try? String(contentsOf: svgDir.appending(path: "\(name).svg"), encoding: .utf8) else {
        fail("missing ThirdParty/phosphor/regular/\(name).svg (run with --vendor)")
    }
    guard svg.contains(#"viewBox="0 0 256 256""#) else { fail("\(name).svg: unexpected viewBox") }
    let range = NSRange(svg.startIndex..., in: svg)
    for m in elementPattern.matches(in: svg, range: range) {
        let tag = String(svg[Range(m.range(at: 1), in: svg)!])
        guard tag == "svg" || tag == "path" else { fail("\(name).svg: unsupported element <\(tag)>") }
    }
    let ds = dPattern.matches(in: svg, range: range).map { String(svg[Range($0.range(at: 1), in: svg)!]) }
    guard !ds.isEmpty else { fail("\(name).svg: no path data") }
    entries.append((name, ds.joined(separator: " ")))
}

var swift = """
// GENERATED by scripts/gen-icons.swift from ThirdParty/phosphor/regular. Do not edit.
// Phosphor Icons, MIT licence; see THIRD-PARTY-NOTICES.

enum PhosphorGlyphs {
    /// Upstream icon name → SVG path data on a 256 × 256 grid (y down), filled non-zero.
    static let pathData: [String: String] = [

"""
for (name, d) in entries { swift += "        \"\(name)\": \"\(d)\",\n" }
swift += "    ]\n}\n"
do {
    try swift.write(to: root.appending(path: "Sources/ShotzCore/Icons/PhosphorGlyphs.generated.swift"), atomically: true, encoding: .utf8)
} catch { fail("write generated file: \(error)") }

guard let license = try? String(contentsOf: phosphor.appending(path: "LICENSE"), encoding: .utf8),
      let source = try? String(contentsOf: phosphor.appending(path: "SOURCE"), encoding: .utf8) else {
    fail("ThirdParty/phosphor/LICENSE or SOURCE missing")
}
let notices = """
